"""Energy balance for the baseline kiln, on a coal net-heating-value basis.

The ledger is written against coal NHV rather than against a "heat generated by
reactions" figure, because NHV is measured, unambiguous and auditable, whereas
"reaction heat" depends on which reaction set and which volatile-matter surrogate
an author picks. Dey et al. (2015) model V.M. as phenol, for instance, which is
not reproducible from proximate analysis alone.

    coal NHV in  =  chemical energy leaving unburnt
                 +  endothermic process demand (reduction, calcination,
                    devolatilisation, moisture evaporation)
                 +  sensible heat in every outgoing stream
                 +  radiation and shell loss
                 +  residual

The residual is reported, not distributed. Hiding a shortfall behind a fudge
factor would make the model look more certain than it is.

Boundary note. This is the KILN boundary, as in Dey et al. (2015). A large share
of coal volatile matter leaves the kiln unburnt and is charged here as energy
crossing the boundary. Dey instead charges only the volatiles' SENSIBLE heat,
because in their accounting the chemical energy is recovered downstream. That
single difference is why closing this ledger calls for ~1.49 t-coal/t-DRI where
Dey measured 1.149: the two balances are drawn around different systems, not in
disagreement about the plant. The volatile terms are therefore labelled "to ABC"
rather than "lost", and src/retrofits/whr.py claims them back as recoverable
heat, which is what the after-burner chamber physically does.
"""
from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", ".."))

from src.data.parameters import (DH_KJ_PER_MOL, GCAL_PER_KJ,
                                 LATENT_HEAT_WATER_KJ_KG, MW)
from src.models.baseline import BaselinePlant

#: Net heating value of carbon oxidised to CO2, kJ/kg C.
C_NHV_KJ_KG = -DH_KJ_PER_MOL["C+O2->CO2"] / MW["C"] * 1000.0
#: Energy still held by CO that has not been burnt through to CO2, kJ/kg C as CO.
CO_RESIDUAL_KJ_KG_C = -DH_KJ_PER_MOL["CO+0.5O2->CO2"] / MW["C"] * 1000.0
#: Net heating value of hydrogen, kJ/kg H2.
H2_NHV_KJ_KG = -DH_KJ_PER_MOL["H2+0.5O2->H2O"] / MW["H2"] * 1000.0
#: Enthalpy to strip oxygen out of haematite all the way to metallic iron,
#: kJ per mol Fe2O3, and only as far as wustite.
DH_FE2O3_TO_FE = 824.2
DH_FE2O3_TO_2FEO = 280.2
#: Mean specific heat of superheated steam, kJ/kg.K.
CP_STEAM_KJ_KGK = 2.0


class EnergyBalance:
    #: Acceptance band for closure, as a fraction of coal NHV.
    TOLERANCE = 0.12

    def __init__(self, plant: BaselinePlant):
        self.plant = plant
        self.p = plant.p

    # ------------------------------------------------------------------
    def _reduction_demand_kj(self) -> float:
        """Enthalpy to remove the oxygen that actually leaves the ore.

        Split between iron taken all the way to metal and iron left as FeO,
        because the two have materially different enthalpies per mole of oxygen.
        """
        p = self.p
        fe_m = 1000.0 * p["dri.fe_metallic_frac"]
        feo = 1000.0 * p["dri.feo_frac"]
        mol_fe2o3_to_fe = (fe_m * 1000.0 / MW["Fe"]) / 2.0
        mol_fe2o3_to_feo = (feo * 1000.0 / MW["FeO"]) / 2.0
        return (mol_fe2o3_to_fe * DH_FE2O3_TO_FE
                + mol_fe2o3_to_feo * DH_FE2O3_TO_2FEO)

    def _sensible(self, mass_kg: float, cp: float, temp_c: float) -> float:
        return mass_kg * cp * (temp_c - self.p["kiln.ambient_temp_c"])

    # ------------------------------------------------------------------
    def calculate_balance(self) -> dict:
        pl, p = self.plant, self.p
        t_gas = p["kiln.waste_gas_temp_c"]
        t_solid = p["dri.discharge_temp_c"]
        vm = (pl.coal_feed * p["coal_feed.volatile_matter"]
              + pl.coal_inj * p["coal_inj.volatile_matter"])

        energy_in = {
            "coal net heating value": pl.nhv_coal_kj,
            "sensible heat in ore": self._sensible(
                pl.ore_wet, p["ore.cp_kj_kgk"], p["kiln.ambient_temp_c"]),
            "sensible heat in coal": self._sensible(
                pl.coal_feed + pl.coal_inj, p["coal.cp_kj_kgk"],
                p["kiln.ambient_temp_c"]),
        }

        # --- chemical energy that walks out of the boundary unburnt -----
        h_unburnt = pl.h_coal - pl.h_burnt_kiln
        c_to_co = pl.c_gasified * p["kiln.co_in_waste_gas_frac"]
        # Two kinds of chemical energy leave the kiln, and they are not
        # equivalent. Carbon locked into solids is gone for good. Volatiles and
        # CO leave the KILN unburnt but are post-combusted in the after-burner
        # chamber, so on a whole-plant basis they are a transfer, not a loss --
        # and they are precisely what makes waste-heat recovery worthwhile.
        chemical_out = {
            "carbon in char (lost)": pl.c_char * C_NHV_KJ_KG,
            "carbon in flue dust (lost)": pl.c_dust * C_NHV_KJ_KG,
            "carbon in DRI (lost)": pl.c_dri * C_NHV_KJ_KG,
            "volatile carbon to ABC": pl.c_unburnt_vm * C_NHV_KJ_KG,
            "volatile hydrogen to ABC": h_unburnt * H2_NHV_KJ_KG,
            "CO slip to ABC": c_to_co * CO_RESIDUAL_KJ_KG_C,
        }

        # --- endothermic process demand ---------------------------------
        mol_dolomite = pl.dolomite_mass * 1000.0 / MW["dolomite"]
        process_demand = {
            "reduction of iron oxides": self._reduction_demand_kj(),
            "dolomite calcination": (
                mol_dolomite * DH_KJ_PER_MOL["dolomite->CaO+MgO+2CO2"]),
            "coal devolatilisation": vm * p["coal.devolatilization_kj_per_kg_vm"],
            "evaporation of feed moisture": pl.moisture_total * (
                LATENT_HEAT_WATER_KJ_KG + CP_STEAM_KJ_KGK * (t_gas - 100.0)),
        }

        # --- sensible heat in outgoing streams --------------------------
        sensible_out = {
            "DRI": self._sensible(1000.0, p["dri.cp_kj_kgk"], t_solid),
            "char (dolochar)": self._sensible(
                pl.char_mass, p["char.cp_kj_kgk"], t_solid),
            "free ash to cooler": self._sensible(
                pl.free_ash, p["char.cp_kj_kgk"], t_solid),
            "unreduced fines": self._sensible(
                pl.other_fines, p["char.cp_kj_kgk"], t_solid),
            "calcined flux": self._sensible(
                pl.cao_out, p["dolomite.cao_cp_kj_kgk"], t_solid),
            "flue dust": self._sensible(
                pl.dust_mass, p["char.cp_kj_kgk"], t_gas),
            "waste gas": self._sensible(
                pl.waste_gas, p["kiln.waste_gas_cp_kj_kgk"], t_gas),
        }

        losses = {
            "radiation and shell loss": (
                pl.nhv_coal_kj * p["kiln.radiation_loss_frac"]),
        }

        total_in = sum(energy_in.values())
        total_out = (sum(chemical_out.values()) + sum(process_demand.values())
                     + sum(sensible_out.values()) + sum(losses.values()))
        residual = total_in - total_out

        g = GCAL_PER_KJ
        return {
            "energy_in_kj_per_t_dri": total_in,
            "energy_out_kj_per_t_dri": total_out,
            "residual_kj_per_t_dri": residual,
            "energy_in_gcal_per_t_dri": total_in * g,
            "energy_out_gcal_per_t_dri": total_out * g,
            "residual_gcal_per_t_dri": residual * g,
            "closure_error_percent": abs(residual) / total_in * 100.0,
            "is_valid": abs(residual) / total_in <= self.TOLERANCE,
            "tolerance_percent": self.TOLERANCE * 100.0,
            "sec_gcal_per_t_dri": pl.nhv_coal_kj * g,
            # Shares, for comparison against published breakdowns.
            "waste_gas_sensible_frac_of_nhv": (
                sensible_out["waste gas"] / pl.nhv_coal_kj),
            "chemical_loss_frac_of_nhv": (
                sum(chemical_out.values()) / pl.nhv_coal_kj),
            "sensible_loss_frac_of_nhv": (
                sum(sensible_out.values()) / pl.nhv_coal_kj),
            "process_demand_frac_of_nhv": (
                sum(process_demand.values()) / pl.nhv_coal_kj),
            # Heat available to a downstream WHR boiler, before the ABC.
            "waste_gas_sensible_kj": sensible_out["waste gas"],
            "recoverable_chemical_kj": (
                chemical_out["volatile carbon to ABC"]
                + chemical_out["volatile hydrogen to ABC"]
                + chemical_out["CO slip to ABC"]),
            "solid_carbon_loss_kj": (
                chemical_out["carbon in char (lost)"]
                + chemical_out["carbon in flue dust (lost)"]
                + chemical_out["carbon in DRI (lost)"]),
            "items": {
                "in": energy_in,
                "chemical energy out (unburnt)": chemical_out,
                "endothermic process demand": process_demand,
                "sensible heat out": sensible_out,
                "losses": losses,
            },
        }

    # ------------------------------------------------------------------
    def closure_driver(self) -> dict:
        """Report the unburnt-V.M.-carbon fraction that would close the balance.

        This is the dominant free parameter: it alone moves roughly a third of
        coal NHV. Exposing the closing value makes the calibration explicit
        instead of burying it in a tuned default.
        """
        base = self.p["kiln.unburnt_vm_carbon_frac"]
        lo, hi = self.p.bounds("kiln.unburnt_vm_carbon_frac")
        best, best_err = base, None
        for i in range(201):
            trial = lo + (hi - lo) * i / 200.0
            pl = BaselinePlant(self.p.with_overrides(
                {"kiln.unburnt_vm_carbon_frac": trial}),
                self.plant.capacity_tpd, self.plant.utilization)
            err = abs(EnergyBalance(pl).calculate_balance()["residual_kj_per_t_dri"])
            if best_err is None or err < best_err:
                best, best_err = trial, err
        return {
            "config_value": base,
            "closing_value": best,
            "search_range": (lo, hi),
            "residual_at_closing_kj": best_err,
        }


if __name__ == "__main__":
    plant = BaselinePlant(capacity_tpd=100, utilization=0.9)
    eb = EnergyBalance(plant)
    r = eb.calculate_balance()
    for group, items in r["items"].items():
        print(f"\n{group.upper()}")
        for k, v in items.items():
            print(f"  {k:34s} {v * GCAL_PER_KJ:8.4f} Gcal/t  "
                  f"{v / plant.nhv_coal_kj * 100:6.2f}% of NHV")
    print(f"\n  {'TOTAL IN':34s} {r['energy_in_gcal_per_t_dri']:8.4f} Gcal/t")
    print(f"  {'TOTAL OUT':34s} {r['energy_out_gcal_per_t_dri']:8.4f} Gcal/t")
    print(f"  {'RESIDUAL':34s} {r['residual_gcal_per_t_dri']:8.4f} Gcal/t  "
          f"({r['closure_error_percent']:.2f}%, valid={r['is_valid']})")
    print(f"\n  SEC {r['sec_gcal_per_t_dri']:.3f} Gcal/t DRI")
    print(f"  waste-gas sensible = {r['waste_gas_sensible_frac_of_nhv'] * 100:.1f}% of coal NHV")
